def parse_trades(data_str):
    trades = []
    lines = data_str.strip().split('\n')
    for line in lines:
        parts = line.split('\t')
        if len(parts) >= 12:
            try:
                symbol = parts[4]
                net_profit = float(parts[11].replace(' ', ''))
                trades.append({'symbol': symbol, 'net_profit': net_profit})
            except ValueError:
                continue
    return trades

trades = parse_trades(data)

